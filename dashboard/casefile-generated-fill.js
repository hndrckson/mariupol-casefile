  const upsertById = (target, rows) => {
    rows.forEach((row) => {
      const index = target.findIndex((item) => item.id === row.id);
      if (index >= 0) {
        target[index] = { ...target[index], ...row };
      } else {
        target.push(row);
      }
    });
  };

  const pushUnique = (target, values) => {
    values.forEach((value) => {
      if (!target.includes(value)) target.push(value);
    });
  };

